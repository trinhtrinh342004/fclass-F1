-- 11. Realtime setup
do $$
declare
  target_table text;
begin
  foreach target_table in array array[
    'profiles',
    'classes',
    'class_memberships',
    'lessons',
    'student_lesson_progress',
    'student_activity_logs'
  ]
  loop
    if not exists (
      select 1
      from pg_publication_tables
      where pubname = 'supabase_realtime'
        and schemaname = 'public'
        and tablename = target_table
    ) then
      execute format('alter publication supabase_realtime add table public.%I', target_table);
    end if;
  end loop;
end $$;

-- 12. Safe Admin promotion script
do $$
declare
  admin_uid uuid;
begin
  select id into admin_uid
  from auth.users
  where email = 'admin@gmail.com'
  limit 1;

  if admin_uid is not null then
    insert into public.profiles (id, full_name, email, role, status)
    values (admin_uid, 'Admin', 'admin@gmail.com', 'admin', 'approved')
    on conflict (id) do update
    set role = 'admin',
        status = 'approved',
        full_name = 'Admin',
        email = 'admin@gmail.com';
    raise notice 'Successfully promoted admin@gmail.com to admin.';
  else
    raise notice 'User admin@gmail.com does not exist in auth.users. Cannot promote to admin.';
  end if;
end $$;
