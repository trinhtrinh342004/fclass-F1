-- Setup extensions
create extension if not exists pgcrypto;

-- 1. Profiles Table
create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  email text,
  full_name text,
  phone text,
  role text not null default 'student',
  status text not null default 'pending',
  note text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

alter table public.profiles drop constraint if exists profiles_role_check;
alter table public.profiles add constraint profiles_role_check check (role in ('admin', 'student'));

alter table public.profiles drop constraint if exists profiles_status_check;
alter table public.profiles add constraint profiles_status_check check (status in ('pending', 'approved', 'rejected'));

alter table public.profiles drop constraint if exists profiles_email_key;
alter table public.profiles add constraint profiles_email_key unique (email);

-- 2. Classes Table
create table if not exists public.classes (
  id uuid default gen_random_uuid() primary key,
  name text not null,
  description text,
  level text default 'A1',
  status text not null default 'active',
  created_by uuid references auth.users(id) on delete set null default auth.uid(),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

alter table public.classes drop constraint if exists classes_status_check;
alter table public.classes add constraint classes_status_check check (status in ('active', 'archived'));

-- 3. Class Memberships Table
create table if not exists public.class_memberships (
  id uuid default gen_random_uuid() primary key,
  class_id uuid not null references public.classes(id) on delete cascade,
  student_id uuid not null references auth.users(id) on delete cascade,
  status text not null default 'pending',
  approved_by uuid references auth.users(id) on delete set null,
  approved_at timestamptz,
  rejected_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique(class_id, student_id)
);

alter table public.class_memberships drop constraint if exists class_memberships_status_check;
alter table public.class_memberships add constraint class_memberships_status_check check (status in ('pending', 'approved', 'rejected', 'removed'));

-- 4. Lessons Table
create table if not exists public.lessons (
  id bigint generated by default as identity primary key,
  lesson_number int not null unique,
  slug text not null unique,
  title text not null,
  topic_english text not null,
  topic_vietnamese text not null,
  description text,
  status text not null default 'draft',
  content jsonb not null default '{}'::jsonb,
  source_lessons jsonb not null default '[]'::jsonb,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

alter table public.lessons drop constraint if exists lessons_status_check;
alter table public.lessons add constraint lessons_status_check check (status in ('ready', 'partial', 'draft', 'empty', 'reused', 'merged'));

-- 5. Student Lesson Progress Table
create table if not exists public.student_lesson_progress (
  id uuid default gen_random_uuid() primary key,
  student_id uuid not null references auth.users(id) on delete cascade,
  class_id uuid references public.classes(id) on delete set null,
  lesson_id bigint not null references public.lessons(id) on delete cascade,
  status text not null default 'not_started',
  progress_percent int not null default 0,
  completed_at timestamptz,
  last_opened_at timestamptz,
  data jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique(student_id, lesson_id)
);

alter table public.student_lesson_progress drop constraint if exists student_lesson_progress_status_check;
alter table public.student_lesson_progress add constraint student_lesson_progress_status_check check (status in ('not_started', 'in_progress', 'completed'));

alter table public.student_lesson_progress drop constraint if exists student_lesson_progress_percent_check;
alter table public.student_lesson_progress add constraint student_lesson_progress_percent_check check (progress_percent between 0 and 100);

-- 6. Student Activity Logs Table
create table if not exists public.student_activity_logs (
  id uuid default gen_random_uuid() primary key,
  student_id uuid references auth.users(id) on delete cascade,
  lesson_id bigint references public.lessons(id) on delete set null,
  action text not null,
  metadata jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);

